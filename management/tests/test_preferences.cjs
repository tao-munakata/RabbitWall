"use strict";
const assert=require("node:assert/strict");
const {TokenPreference}=require("../taco-console/static/preferences.js");
const data=new Map();
const storage={getItem:key=>data.get(key) ?? null,setItem:(key,value)=>data.set(key,value),removeItem:key=>data.delete(key)};
const preference=new TokenPreference(()=>storage);
assert.deepEqual(preference.read(),{token:"",error:false});
preference.save("test-only-operation-key",false);assert.equal(data.size,0);
assert.deepEqual(preference.save("test-only-operation-key",true),{saved:true,error:false});
assert.equal(new TokenPreference(()=>storage).read().token,"test-only-operation-key");
preference.save("replacement-test-key",true);assert.equal(preference.read().token,"replacement-test-key");
preference.save("replacement-test-key",false);assert.equal(preference.read().token,"");
preference.save("test-only-operation-key",true);preference.save("",false);assert.equal(data.size,0);
const denied=new TokenPreference(()=>{throw new Error("storage denied");});
assert.deepEqual(denied.read(),{token:"",error:true});
assert.deepEqual(denied.save("test-only-operation-key",true),{saved:false,error:true});
assert.deepEqual(denied.save("",false),{saved:false,error:true});
console.log("Token preference: opt-in persistence, reload, replace, forget, and unavailable storage passed.");
